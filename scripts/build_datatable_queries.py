"""Builds standalone learner queries (SC-200/lab-queries/*.datatable.kql) from detections/*.kql.
Each output embeds the synthetic sample rows via the KQL `datatable` operator and drops the
`TimeGenerated > ago(1d)` filter, so it can run in any Log Analytics query window without ingesting data.
Run:  python scripts/build_datatable_queries.py          (use --check to verify files are up to date)"""
import csv, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SAMPLES = ROOT / "sample-data"
OUT = ROOT / "SC-200" / "lab-queries"

SCHEMAS = {
    "SigninLogs": ("signinlogs_sample.csv", {"TimeGenerated": "datetime", "UserPrincipalName": "string", "IPAddress": "string", "ResultType": "string", "AppDisplayName": "string"}),
    "AuditLogs": ("auditlogs_sample.jsonl", {"TimeGenerated": "datetime", "OperationName": "string", "InitiatedBy": "dynamic", "TargetResources": "dynamic", "CorrelationId": "string"}),
    "DeviceProcessEvents": ("deviceprocessevents_sample.csv", {"TimeGenerated": "datetime", "DeviceName": "string", "AccountName": "string", "FileName": "string", "ProcessCommandLine": "string", "InitiatingProcessFileName": "string"}),
    "AzureActivity": ("azureactivity_sample.csv", {"TimeGenerated": "datetime", "OperationNameValue": "string", "ActivityStatusValue": "string", "Caller": "string", "CallerIpAddress": "string", "ResourceGroup": "string", "ResourceProviderValue": "string"}),
}

def literal(value, kind):
    if kind == "datetime":
        return f"datetime({value.rstrip('Z')}Z)" if isinstance(value, str) else str(value)
    if kind == "dynamic":
        return f"dynamic({json.dumps(value)})"
    return json.dumps(value)

def load_rows(fname):
    p = SAMPLES / fname
    if fname.endswith(".jsonl"):
        return [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
    with open(p, newline="") as f:
        return list(csv.DictReader(f))

def datatable_let(table):
    fname, schema = SCHEMAS[table]
    cols = ", ".join(f"{c}:{t}" for c, t in schema.items())
    lines = []
    for r in load_rows(fname):
        lines.append("    " + ", ".join(literal(r[c], t) for c, t in schema.items()))
    return f"let {table} = datatable({cols}) [\n" + ",\n".join(lines) + "\n];\n"

def build(det_path):
    text = det_path.read_text()
    table = re.search(r"^// Tables:\s*(\w+)", text, re.M).group(1)
    header = [l for l in text.splitlines() if l.startswith("//")]
    body = [l for l in text.splitlines() if not l.startswith("//")]
    body = [l for l in body if not re.match(r"^\s*\|\s*where TimeGenerated > ago\(1d\)\s*$", l)]
    banner = ["// LEARNER VERSION: runs on embedded SYNTHETIC rows (no ingestion needed). Generated by scripts/build_datatable_queries.py - do not edit by hand."]
    return "\n".join(banner + header) + "\n" + datatable_let(table) + "\n".join(body) + "\n"

def main(check=False):
    OUT.mkdir(parents=True, exist_ok=True)
    ok = True
    for det in sorted((ROOT / "detections").glob("*.kql")):
        target = OUT / (det.stem + ".datatable.kql")
        content = build(det)
        if check:
            ok &= target.exists() and target.read_text() == content
        else:
            target.write_text(content)
    return ok

if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(0 if main(check=True) else 1)
    main()
    print("datatable queries written to", OUT)
